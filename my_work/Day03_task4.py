# арифметические операторы
a = 10
b = 5

print(a + b)   #    Сложение
print(a - b)   #    Вычитание
print(a * b)   #    Умножение
print(a / b)   #    Деление (always float)
print(a // b)  #    Кратное деление (округление в меньшую сторону 7//2 = 3)
print(a % b)   #    Остаток по модулю 
print(a ** b)  #    Возведение в степень

